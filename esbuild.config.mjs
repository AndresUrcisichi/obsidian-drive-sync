import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	// Optional build-time defaults (from .env, never committed) so a personal
	// build only needs "Sign in with Google" on each device.
	define: {
		__GDVS_CLIENT_ID__: JSON.stringify(process.env.GDVS_CLIENT_ID ?? ''),
		__GDVS_CLIENT_SECRET__: JSON.stringify(
			process.env.GDVS_CLIENT_SECRET ?? '',
		),
		__GDVS_REDIRECT_URI__: JSON.stringify(
			process.env.GDVS_REDIRECT_URI ?? '',
		),
	},
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
